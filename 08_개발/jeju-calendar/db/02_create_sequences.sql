-- 02. 시퀀스 생성 (SEQ_ + 테이블명)
-- 숫자 하나로 된 PK를 가진 테이블 9개에만 만듦
-- REGION은 지역 코드(REGION_CODE)가 PK이고,
-- BUSINESS_PERMISSION, DATA_VALIDATION_RESULT, PROMO_SUGGESTION_ITEM은 복합 PK라 시퀀스를 만들지 않음

CREATE SEQUENCE SEQ_USERS                   START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_BUSINESS                START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_DATA_SOURCE             START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_RECOMMENDATION_CRITERIA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_PROMO_SUGGESTION        START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_PROMO_PLAN              START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_EXECUTION_RECORD        START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_REGION_MONTHLY_STAT     START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_REGION_CONSUMPTION_STAT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
