CREATE TABLE IJTO_DATA_SNAPSHOT
(
    SNAPSHOT_KEY VARCHAR2(100 CHAR) NOT NULL,
    REPOSITORY VARCHAR2(200 CHAR) NOT NULL,
    COMMIT_SHA CHAR(40) NOT NULL,
    FILE_PATH VARCHAR2(300 CHAR) NOT NULL,
    CONTENT_SHA256 CHAR(64) NOT NULL,
    SNAPSHOT_DATE DATE NOT NULL,
    PAYLOAD CLOB NOT NULL,
    IMPORTED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_IJTO_DATA_SNAPSHOT PRIMARY KEY (SNAPSHOT_KEY)
);
